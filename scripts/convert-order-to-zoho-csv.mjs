/**
 * convert-order-to-zoho-csv.mjs
 *
 * Converts a client-filled order CSV (output of generate-client-order-template.mjs)
 * into a Zoho Inventory Sales Order import CSV.
 *
 * Usage:
 *   node scripts/convert-order-to-zoho-csv.mjs <filled-order.csv>
 *   node scripts/convert-order-to-zoho-csv.mjs <filled-order.csv> --customer "Client Name"
 *   node scripts/convert-order-to-zoho-csv.mjs <filled-order.csv> --out zoho-import.csv --date 2026-03-10
 *
 * Required:
 *   <input>        Path to the client-filled CSV
 *
 * Optional:
 *   --customer     Customer name (overrides value in CSV; required if CSV has no Client Name)
 *   --out          Output file path (default: zoho-sales-order-<date>.csv)
 *   --date         Sales order date in YYYY-MM-DD format (default: today)
 *   --order-no     Sales order number (default: auto — Zoho assigns one)
 *
 * Client info parsed from CSV (generated by generate-client-order-template.mjs):
 *   Client Name, Contact Number, Email, VAT Number, Shipping Address, Invoice / Billing Address
 *
 * Output matches Zoho Inventory "Sales Orders" import format plus address/notes columns.
 */

import { readFileSync, mkdirSync, writeFileSync } from 'fs'
import { resolve, dirname, basename } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))

// ── Helpers ───────────────────────────────────────────────────────────────────
function getArg(name) {
  const i = process.argv.indexOf(name)
  return i !== -1 ? process.argv[i + 1] ?? null : null
}

function fail(msg) {
  console.error(`ERROR: ${msg}`)
  process.exit(1)
}

function csvCell(value) {
  const str = String(value ?? '')
  if (/[",\n\r]/.test(str)) return `"${str.replace(/"/g, '""')}"`
  return str
}

function formatDate(dateStr) {
  // Zoho Inventory accepts DD/MM/YYYY or MM/DD/YYYY depending on org settings.
  // We output YYYY-MM-DD which is unambiguous and accepted by Zoho.
  return dateStr
}

// ── Args ──────────────────────────────────────────────────────────────────────
const inputArg = process.argv[2]
if (!inputArg || inputArg.startsWith('--')) {
  fail('Missing input file. Usage: node scripts/convert-order-to-zoho-csv.mjs <filled-order.csv> --customer "Name"')
}

const customerArg = getArg('--customer') // optional override

const dateArg = getArg('--date') || new Date().toISOString().slice(0, 10)
const orderNo = getArg('--order-no') || ''
const inputPath = resolve(inputArg)

const defaultOutName = `zoho-sales-order-${dateArg}.csv`
const outArg = getArg('--out')
const outputPath = resolve(outArg || defaultOutName)

// ── Parse input CSV ───────────────────────────────────────────────────────────
let rawText
try {
  rawText = readFileSync(inputPath, 'utf8')
} catch (e) {
  fail(`Could not read input file: ${inputPath}\n${e.message}`)
}

// Simple but robust CSV parser (handles quoted fields with commas inside)
function parseCsv(text) {
  const lines = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n')
  return lines
    .filter(l => l.trim() !== '')
    .map(line => {
      const cells = []
      let cur = ''
      let inQuotes = false
      for (let i = 0; i < line.length; i++) {
        const ch = line[i]
        if (ch === '"') {
          if (inQuotes && line[i + 1] === '"') { cur += '"'; i++ }
          else { inQuotes = !inQuotes }
        } else if (ch === ',' && !inQuotes) {
          cells.push(cur); cur = ''
        } else {
          cur += ch
        }
      }
      cells.push(cur)
      return cells
    })
}

const allRows = parseCsv(rawText)
if (allRows.length < 2) fail('Input CSV appears empty or has no data rows.')

// ── Parse client info block ───────────────────────────────────────────────────
// Rows before the product header (the row whose first cell is "SKU") are treated
// as key: value pairs from the CLIENT INFORMATION section.
const CLIENT_INFO_KEYS = {
  'client name':              'clientName',
  'contact number':           'contactNumber',
  'email':                    'email',
  'vat number':               'vatNumber',
  'shipping address':         'shippingAddress',
  'invoice / billing address':'billingAddress',
  'invoice/billing address':  'billingAddress',
  'billing address':          'billingAddress',
  'invoice address':          'billingAddress',
}

const clientInfo = {}
let productHeaderIdx = -1

for (let i = 0; i < allRows.length; i++) {
  const row = allRows[i]
  const first = (row[0] ?? '').trim()
  // Product header row detected when first cell is exactly "SKU"
  if (first.toLowerCase() === 'sku') {
    productHeaderIdx = i
    break
  }
  // Try to parse as "Label:", value
  const labelRaw = first.replace(/:$/, '').trim().toLowerCase()
  const value    = (row[1] ?? '').trim()
  if (CLIENT_INFO_KEYS[labelRaw] && value) {
    clientInfo[CLIENT_INFO_KEYS[labelRaw]] = value
  }
}

if (productHeaderIdx === -1) fail('Could not find SKU header row in input CSV.')

// Resolve customer name: CLI arg wins, then CSV field, then error
const customer = customerArg || clientInfo.clientName
if (!customer) {
  fail('No customer name found. Fill in "Client Name" in the CSV or pass --customer "Name".')
}

if (Object.keys(clientInfo).length > 0) {
  console.log('  Client info read from CSV:')
  for (const [k, v] of Object.entries(clientInfo)) console.log(`    ${k}: ${v}`)
  if (customerArg && customerArg !== clientInfo.clientName) {
    console.log(`  (--customer override applied: "${customerArg}")`)
  }
  console.log()
}

// Map headers (case-insensitive)
const headerRow = allRows[productHeaderIdx].map(h => h.trim().toLowerCase())

function findCol(candidates) {
  for (const c of candidates) {
    const i = headerRow.findIndex(h => h.includes(c.toLowerCase()))
    if (i !== -1) return i
  }
  return -1
}

const colSku       = findCol(['sku'])
const colName      = findCol(['item name', 'name', 'product name'])
const colPrice     = findCol(['unit price', 'price', 'rate', 'item cost'])
const colQty       = findCol(['qty', 'quantity'])

if (colSku === -1)   fail('Could not find SKU column in input CSV.')
if (colName === -1)  fail('Could not find Item Name column in input CSV.')
if (colPrice === -1) fail('Could not find Unit Price column in input CSV.')
if (colQty === -1)   fail('Could not find Qty column in input CSV.')

// ── Filter rows with qty > 0 ──────────────────────────────────────────────────
const dataRows = allRows.slice(productHeaderIdx + 1)
const orderLines = []

for (let i = 0; i < dataRows.length; i++) {
  const row = dataRows[i]
  const qtyRaw = (row[colQty] ?? '').trim()
  if (qtyRaw === '' || qtyRaw === '0') continue

  const qty = Number(qtyRaw)
  if (!Number.isFinite(qty) || qty <= 0) {
    console.warn(`  Warning: Row ${i + 2} has invalid Qty "${qtyRaw}" — skipped.`)
    continue
  }

  const sku   = (row[colSku]   ?? '').trim()
  const name  = (row[colName]  ?? '').trim()
  const price = parseFloat((row[colPrice] ?? '0').trim().replace(/[^0-9.]/g, ''))

  if (!sku && !name) {
    console.warn(`  Warning: Row ${i + 2} has no SKU or Name — skipped.`)
    continue
  }

  orderLines.push({ sku, name, price, qty, total: +(price * qty).toFixed(2) })
}

if (orderLines.length === 0) {
  fail('No rows with Qty > 0 found in the input CSV. Did the client fill in quantities?')
}

// ── Build Zoho Sales Order CSV ────────────────────────────────────────────────
// Zoho Inventory Sales Order import columns.
// Order-level fields (SalesOrder#, Date, CustomerName, addresses, Notes) are
// only populated on the FIRST line item row; subsequent rows leave them blank.

// Build a Notes string from client info fields that don't have dedicated columns
const notesParts = []
if (clientInfo.contactNumber) notesParts.push(`Contact: ${clientInfo.contactNumber}`)
if (clientInfo.email)         notesParts.push(`Email: ${clientInfo.email}`)
if (clientInfo.vatNumber)     notesParts.push(`VAT: ${clientInfo.vatNumber}`)
const notes = notesParts.join(' | ')

const zohoHeader = [
  'SalesOrder#',
  'Date',
  'CustomerName',
  'BillingAddress',
  'ShippingAddress',
  'Notes',
  'Item Name',
  'SKU',
  'Quantity',
  'Rate',
  'Item Total',
]

const zohoRows = orderLines.map((line, idx) => [
  csvCell(idx === 0 ? orderNo : ''),
  csvCell(idx === 0 ? formatDate(dateArg) : ''),
  csvCell(idx === 0 ? customer : ''),
  csvCell(idx === 0 ? (clientInfo.billingAddress  || '') : ''),
  csvCell(idx === 0 ? (clientInfo.shippingAddress || '') : ''),
  csvCell(idx === 0 ? notes : ''),
  csvCell(line.name),
  csvCell(line.sku),
  csvCell(line.qty),
  csvCell(line.price.toFixed(2)),
  csvCell(line.total.toFixed(2)),
])

const totalUnits = orderLines.reduce((s, l) => s + l.qty, 0)
const totalValue = orderLines.reduce((s, l) => s + l.total, 0)

const csv = [
  zohoHeader.join(','),
  ...zohoRows.map(r => r.join(',')),
].join('\r\n')

// ── Write output ──────────────────────────────────────────────────────────────
try {
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, csv, 'utf8')
} catch (e) {
  fail(`Could not write output to ${outputPath}\n${e.message}`)
}

console.log(`✓ Zoho Sales Order CSV written to: ${outputPath}`)
console.log()
console.log(`  Customer        : ${customer}`)
if (clientInfo.contactNumber)  console.log(`  Contact         : ${clientInfo.contactNumber}`)
if (clientInfo.email)          console.log(`  Email           : ${clientInfo.email}`)
if (clientInfo.vatNumber)      console.log(`  VAT             : ${clientInfo.vatNumber}`)
if (clientInfo.shippingAddress) console.log(`  Shipping Address: ${clientInfo.shippingAddress}`)
if (clientInfo.billingAddress)  console.log(`  Billing Address : ${clientInfo.billingAddress}`)
console.log(`  Date            : ${dateArg}`)
console.log(`  Line items      : ${orderLines.length}`)
console.log(`  Total qty       : ${totalUnits} units`)
console.log(`  Total value     : R${totalValue.toFixed(2)}`)
console.log()
console.log('Import steps in Zoho Inventory:')
console.log('  1. Sales Orders → ⋮ (more) → Import Sales Orders')
console.log('  2. Upload this CSV file')
console.log('  3. Confirm column mapping and import')
