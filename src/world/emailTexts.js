export const TEXTS = { en, el, bg, it, es, ro, pl, fr, de, pt, hu }

export function tr(lang, key, vars = {}) {
  let s = (TEXTS[lang] || en)[key] ?? en[key] ?? key
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v ?? ''))
  return s
}
