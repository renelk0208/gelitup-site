export const WORLD_STRINGS = { en, el, bg, it, es, ro, pl, fr, de, pt, hu }
export const WORLD_LANGS = Object.keys(WORLD_STRINGS)

export function makeT(lang) {
  const dict = WORLD_STRINGS[lang] || en
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}

/** Pick a round's title/description in the viewer's language, falling back to English. */
export function localized(field, lang) {
  if (!field || typeof field !== 'object') return field || ''
  return field[lang] || field.en || Object.values(field)[0] || ''
}
