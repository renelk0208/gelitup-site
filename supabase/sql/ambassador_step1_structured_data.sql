-- Ambassador admin, step 1: give programme data proper columns and tables.
--
-- Until now the ambassador type, pause details, factory acknowledgement, next
-- package date and every shipped package lived as [TAG:value] lines inside the
-- free-text admin_comment column. This migration only ADDS structure; nothing
-- is dropped or rewritten, so the previous site build keeps working unchanged.
--
-- Run once in the Supabase SQL Editor, then run
--   node scripts/backfill-ambassador-step1.mjs            (dry run, writes a report)
--   node scripts/backfill-ambassador-step1.mjs --apply    (copies the data across)
-- Safe to re-run: every statement is idempotent.

-- ── 1. New columns on ambassador_applications ───────────────────────────────
alter table public.ambassador_applications
  add column if not exists ambassador_type   text,
  add column if not exists factory_ack_at    timestamptz,
  add column if not exists factory_ack_by    text,
  add column if not exists paused_at         timestamptz,
  add column if not exists paused_by         text,
  add column if not exists paused_reason     text,
  add column if not exists next_package_due  date;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'ambassador_applications_type_check'
  ) then
    alter table public.ambassador_applications
      add constraint ambassador_applications_type_check
      check (ambassador_type is null or ambassador_type in
        ('standard_ambassador', 'super_ambassador', 'extreme_ambassador'));
  end if;
end $$;

create index if not exists idx_ambassador_applications_next_package_due
  on public.ambassador_applications (next_package_due)
  where status = 'approved';

-- ── 2. One row per package: ambassador_shipments ────────────────────────────
create table if not exists public.ambassador_shipments (
  id               bigint generated by default as identity primary key,
  application_id   bigint not null
                   references public.ambassador_applications(id) on delete cascade,
  status           text not null default 'sent' check (status in ('planned', 'sent')),
  ambassador_type  text,
  items            text[] not null default '{}',
  method           text not null default 'courier'
                   check (method in ('courier', 'post_office', 'other')),
  tracking_number  text,
  tracking_url     text,
  planned_for      date,
  sent_at          timestamptz,
  created_by       text,
  created_at       timestamptz not null default now(),
  -- Set when a row was copied from an old "📦 Shipped" admin_comment line, so
  -- the backfill never inserts the same package twice.
  legacy_source    text
);

create index if not exists idx_ambassador_shipments_application
  on public.ambassador_shipments (application_id, sent_at desc);

create unique index if not exists idx_ambassador_shipments_legacy_source
  on public.ambassador_shipments (application_id, legacy_source)
  where legacy_source is not null;

alter table public.ambassador_shipments enable row level security;

-- Admins (b2b_admins) can do everything.
drop policy if exists "ambassador_shipments_admin_all" on public.ambassador_shipments;
create policy "ambassador_shipments_admin_all"
  on public.ambassador_shipments
  for all
  to authenticated
  using (exists (select 1 from public.b2b_admins a where lower(a.email) = lower(auth.email())))
  with check (exists (select 1 from public.b2b_admins a where lower(a.email) = lower(auth.email())));

-- An ambassador signed in to the portal reads their own SENT packages through
-- this function, matched by the email on their application. (A function is
-- used instead of a select policy so admins viewing the portal never see
-- everyone's packages, and so it works without read access to applications.)
drop policy if exists "ambassador_shipments_owner_select" on public.ambassador_shipments;

create or replace function public.get_my_ambassador_shipments()
returns table (
  id bigint,
  items text[],
  method text,
  tracking_number text,
  tracking_url text,
  sent_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select s.id, s.items, s.method, s.tracking_number, s.tracking_url, s.sent_at
    from public.ambassador_shipments s
    join public.ambassador_applications app on app.id = s.application_id
   where s.status = 'sent'
     and auth.email() is not null
     and lower(trim(app.email)) = lower(trim(auth.email()))
   order by s.sent_at desc nulls last
   limit 24;
$$;

revoke all on function public.get_my_ambassador_shipments() from public;
grant execute on function public.get_my_ambassador_shipments() to authenticated;

-- ── 3. Link discount codes to the ambassador they belong to ─────────────────
alter table public.ambassador_codes
  add column if not exists application_id bigint
    references public.ambassador_applications(id) on delete set null,
  add column if not exists replaced_at timestamptz;

create index if not exists idx_ambassador_codes_application
  on public.ambassador_codes (application_id);

-- Exact-email links are safe to make here; anything fuzzier is left to the
-- backfill script's report for a person to confirm.
update public.ambassador_codes c
   set application_id = app.id
  from public.ambassador_applications app
 where c.application_id is null
   and c.ambassador_email is not null
   and lower(trim(c.ambassador_email)) = lower(trim(app.email))
   and app.status <> 'rejected';

-- Codes created later (by approve_ambassador_application or by hand) get linked
-- automatically by exact email, so the link never has to be guessed again.
create or replace function public.link_ambassador_code_to_application()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.application_id is null and new.ambassador_email is not null then
    select app.id into new.application_id
      from public.ambassador_applications app
     where lower(trim(app.email)) = lower(trim(new.ambassador_email))
       and app.status <> 'rejected'
     order by app.created_at desc
     limit 1;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_link_ambassador_code_to_application on public.ambassador_codes;
create trigger trg_link_ambassador_code_to_application
  before insert or update of ambassador_email, application_id on public.ambassador_codes
  for each row execute function public.link_ambassador_code_to_application();

-- ── 4. Status values: one set (pending, approved, paused, rejected) ─────────
-- The admin already treats new / submitted / reviewing as "pending"; this makes
-- the stored value match what the screen shows, for old rows and new ones.
update public.ambassador_applications
   set status = 'pending'
 where status in ('new', 'submitted', 'reviewing');

alter table public.ambassador_applications alter column status set default 'pending';
